#!/usr/bin/env python3
"""
Check data/connections/grammar/grammar.json against sources.json, then write
docs/symbolic-grammar/GRAMMAR.md, which shows every tradition's reading under each entry.

Usage:  python -I scripts/connections/build_grammar_doc.py
Exit code 1 if the grammar has errors (unknown ids, wrong kinds).
"""
import json
import os
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GDIR = os.path.join(ROOT, "data", "connections", "grammar")
DOC = os.path.join(ROOT, "docs", "symbolic-grammar", "GRAMMAR.md")

TRADITION = {"jordan": "Jordan", "pageau": "Pageau", "leithart": "Leithart", "fathers": "Fathers"}
WORK = {"01": ", TNE", "02": ", TNE", "03": ", SM/RTD", "05": ", talks", "06": ", LoC"}
KIND_ORDER =["axis", "zone", "figure", "role", "act", "state", "number", "sequence"]
KIND_TITLE = {"axis": "Axes", "zone": "Zones", "figure": "Figures", "role": "Roles", "act": "Acts",
              "state": "States", "number": "Numbers", "sequence": "Sequences"}


def check(g, sources):
    errors = []
    ids = {}
    for e in g["entries"]:
        if e["id"] in ids:
            errors.append(f"duplicate id {e['id']}")
        ids[e["id"]] = e
        if e["kind"] not in KIND_ORDER:
            errors.append(f"{e['id']}: unknown kind {e['kind']}")
    for e in g["entries"]:
        for s in e.get("sources", []):
            if s not in sources:
                errors.append(f"{e['id']}: unknown source {s}")
        for rel, targets in (e.get("rel") or {}).items():
            for t in targets:
                if t not in ids:
                    errors.append(f"{e['id']}: rel {rel} -> unknown {t}")
        for i, st in enumerate(e.get("steps", []), 1):
            a = ids.get(st.get("act"))
            if not a or a["kind"] != "act":
                errors.append(f"{e['id']} step {i}: act {st.get('act')} is not an act")
            for w in st.get("who", []) + st.get("with", []):
                if w not in ids or ids[w]["kind"] not in ("role", "figure"):
                    errors.append(f"{e['id']} step {i}: {w} is not a role or figure")
            if "where" in st and (st["where"] not in ids or ids[st["where"]]["kind"] != "zone"):
                errors.append(f"{e['id']} step {i}: {st['where']} is not a zone")
    return ids, errors


def md_entry(e, ids, sources):
    out = [f"### {e['label']}  `{e['id']}`", "", e["def"], ""]
    if e.get("poles"):
        out.append(f"**Poles:** {e['poles'][0]} / {e['poles'][1]}")
    if e.get("texts"):
        out.append(f"**Key texts:** {'; '.join(e['texts'])}")
    if e.get("words"):
        out.append(f"**Words:** {', '.join(e['words'])}")
    for rel, targets in (e.get("rel") or {}).items():
        out.append(f"**{rel.replace('_', ' ').capitalize()}:** " + ", ".join(f"`{t}`" for t in targets))
    if e.get("christ"):
        out.append(f"**Christ:** {e['christ']}")
    if e.get("note"):
        out.append(f"**Note:** {e['note']}")
    if e.get("tension"):
        out.append(f"**Where the readings differ:** {e['tension']}")
    if e.get("steps"):
        out += ["", "| # | Act | Who | Where | Note |", "|---|---|---|---|---|"]
        for i, st in enumerate(e["steps"], 1):
            act = ids[st["act"]]["label"] + (" *(optional)*" if st.get("optional") else "")
            who = ", ".join(ids[w]["label"] for w in st.get("who", []) + st.get("with", []))
            where = ids[st["where"]]["label"] if st.get("where") else ""
            out.append(f"| {i} | {act} | {who} | {where} | {st.get('note', '')} |")
    if e.get("instances"):
        out.append("")
        out.append(f"**Instances:** {'; '.join(e['instances'])}")
    out += ["", "<details><summary>Readings by tradition</summary>", ""]
    by = defaultdict(list)
    for s in e.get("sources", []):
        by[sources[s]["tradition"]].append(sources[s])
    for t in ["jordan", "pageau", "leithart", "fathers"]:
        for src in by.get(t, []):
            where = "; ".join(src["where"][:3])
            work = WORK.get(src["src"][:2], "")
            out.append(f"- **{TRADITION[t]}**{work} ({src['label']}): {src['def']} *{where}*")
    out += ["", "</details>", ""]
    return out


def main():
    g = json.load(open(os.path.join(GDIR, "grammar.json"), encoding="utf-8"))
    sources = json.load(open(os.path.join(GDIR, "sources.json"), encoding="utf-8"))
    ids, errors = check(g, sources)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)

    used = {s for e in g["entries"] for s in e.get("sources", [])}
    unused = sorted(set(sources) - used)
    counts = defaultdict(int)
    for e in g["entries"]:
        counts[e["kind"]] += 1

    lines = [
        "# The symbolic grammar",
        "",
        f"Status: **{g['status']}**. Generated by `scripts/connections/build_grammar_doc.py` from "
        "`data/connections/grammar/grammar.json`; edit the JSON, not this file.",
        "",
        g["about"],
        "",
        f"{len(g['entries'])} entries merge {len(used)} of {len(sources)} source entries. "
        + ", ".join(f"{counts[k]} {KIND_TITLE[k].lower()}" for k in KIND_ORDER) + ".",
        "",
        "Sources: Jordan = *Through New Eyes*, *Symbolism: A Manifesto*, *Rebellion, Tyranny, and Dominion in the "
        "Book of Genesis*. Pageau = Matthieu Pageau, *The Language of Creation*, and the Pageaus' public talks. "
        "Fathers = the ANF/NPNF texts in this repository. Locations only; see `METHOD.md` for how to read them.",
        "",
    ]
    for k in KIND_ORDER:
        group = [e for e in g["entries"] if e["kind"] == k]
        lines += [f"## {KIND_TITLE[k]}", "", g["kinds"][k].capitalize() + ".", ""]
        for e in group:
            lines += md_entry(e, ids, sources)
    lines += ["## Source entries not yet merged", "",
              "These candidate entries from the reading notes are not part of any grammar entry yet. "
              "Some are too specific, some overlap; each is a decision to make.", ""]
    by_t = defaultdict(list)
    for s in unused:
        by_t[sources[s]["tradition"]].append(f"`{s}` {sources[s]['label']}")
    for t, items in by_t.items():
        lines.append(f"**{TRADITION[t]}** ({len(items)}): " + "; ".join(items))
        lines.append("")

    os.makedirs(os.path.dirname(DOC), exist_ok=True)
    with open(DOC, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"ok: {len(g['entries'])} entries, {len(used)} sources used, {len(unused)} not merged; wrote {DOC}",
          file=sys.stderr)


if __name__ == "__main__":
    main()
